import { readFileSync, writeFileSync } from "node:fs";

/**
 * roster.json -> packages/sim/src/kartroster.ts: every course's name, game, cup, theme, laps and phrase aliases, and nothing else. The official names live
 * in that one file (and roster.json), so renaming the whole pack is one edit. Run after roster.ts.
 *   node --no-warnings tools/mariokart/emit.ts
 */
interface Row { id: string; name: string; game: string; cup: string; theme: string; laps: number; lengthM: number | null; features: string[] }
const roster: Row[] = JSON.parse(readFileSync(new URL("./roster.json", import.meta.url), "utf8"));

const GAME_TITLE: Record<string, string> = {
  smk: "Super Mario Kart", mk64: "Mario Kart 64", mksc: "Mario Kart: Super Circuit", mkdd: "Mario Kart: Double Dash!!", mkds: "Mario Kart DS",
  mkwii: "Mario Kart Wii", mk7: "Mario Kart 7", mk8: "Mario Kart 8",
};
/** The ground a theme races on (the grip and braking of the place); the look comes from the theme itself. Kept fair for a kart: only snow and sand change the grip. */
const BIOME: Record<string, string> = { snow: "snow", desert: "desert", city: "city", tech: "city", beach: "grass" };

const normal = (s: string): string => s.toLowerCase().replace(/[.'’]/g, "").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
const rows = roster.map((r) => {
  const bare = normal(r.name);
  // a name two layouts share is only reachable through the game-qualified id
  const shared = roster.filter((o) => normal(o.name) === bare).length > 1;
  const aliases = [...new Set([...(shared ? [] : [bare]), r.id])].filter((a) => a !== r.id);
  return {
    id: r.id, name: r.name, game: r.game, gameTitle: GAME_TITLE[r.game]!, cup: r.cup, theme: r.theme, biome: BIOME[r.theme] ?? "grass", laps: r.laps, aliases,
    blurb: `${r.name} from ${GAME_TITLE[r.game]}, ${r.cup}. A fan approximation of the layout.`,
  };
});
const text = `// GENERATED by tools/mariokart/emit.ts from tools/mariokart/roster.json: do not edit by hand.
// The official course names live here and in roster.json and nowhere else in the game's code.
export interface KartRow { id: string; name: string; game: string; gameTitle: string; cup: string; theme: string; biome: "grass" | "desert" | "snow" | "city"; laps: number; aliases: string[]; blurb: string }
export const KART_ROSTER: KartRow[] = ${JSON.stringify(rows, null, 1).replace(/\n\s+/g, " ").replace(/\},? ?\{/g, "},\n{").replace(/^\[ /, "[\n").replace(/ \]$/, "\n]")};
`;
writeFileSync(new URL("../../packages/sim/src/kartroster.ts", import.meta.url), text);
console.log(`${rows.length} courses written`);
